using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using KandyTourism.Api.Application.Common;

namespace KandyTourism.Api.Infrastructure.Seed;

/// <summary>
/// Generates <c>Infrastructure/SqlScripts/SeedKandyAttractions.sql</c> from <see cref="SeedData"/>, so the
/// standalone script and the runtime seeder can never drift apart. A unit test fails if the committed
/// script differs from this output; regenerate it with <c>dotnet run -- generate-seed-sql</c>.
/// </summary>
public static class SeedSqlScriptGenerator
{
    public const string RelativePath = "Infrastructure/SqlScripts/SeedKandyAttractions.sql";

    private static readonly JsonSerializerOptions JsonOptions = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    private const string AttractionColumns =
        "[Name], [Slug], [CategoryId], [ShortDescription], [Description], [ImageUrl], [ImageAlt], " +
        "[ImageCreditLabel], [ImageCreditSourceUrl], [Address], [Area], [Latitude], [Longitude], " +
        "[CoordinatesApproximate], [EstimatedVisitDurationMinutes], [OpeningHours], [EntranceFee], " +
        "[VisitorTips], [Tags], [SearchText], [IsFeatured], [IsActive], [CreatedAtUtc], [UpdatedAtUtc]";

    public static string Generate()
    {
        var categoryNames = SeedData.Categories.ToDictionary(c => c.Slug, c => c.Name);
        var sql = new StringBuilder();
        void Line(string text = "") => sql.Append(text).Append('\n');

        Line("/*");
        Line("  Kandy Day Trip Planner - seed data for attraction categories, start points and attractions.");
        Line("");
        Line("  GENERATED FILE - do not edit by hand. Source: Infrastructure/Seed/SeedData.cs");
        Line("  Regenerate from the API project folder with:  dotnet run -- generate-seed-sql");
        Line("");
        Line($"  Contents: {SeedData.Categories.Count} categories, {SeedData.StartPresets.Count} start points, " +
             $"{SeedData.Attractions.Count} attractions ({SeedData.Attractions.Sum(a => a.Gallery.Length)} gallery images).");
        Line("");
        Line("  Prerequisites");
        Line("    - SQL Server (LocalDB, Express or full). The schema must already exist: apply the EF Core");
        Line("      migrations first, e.g.  dotnet ef database update");
        Line("");
        Line("  Execution (example, LocalDB). The file is UTF-8; -f 65001 makes sqlcmd read it as UTF-8:");
        Line("    sqlcmd -S \"(localdb)\\MSSQLLocalDB\" -d KandyTourism -f 65001 -b -i SeedKandyAttractions.sql");
        Line("  SSMS / Azure Data Studio: open the file and execute it against the KandyTourism database.");
        Line("");
        Line("  Behaviour");
        Line("    - Idempotent: every record is inserted only if no row with the same slug exists, so the");
        Line("      script can be run repeatedly. Existing rows - including admin edits and attractions an");
        Line("      admin has deleted (deactivated) - are never updated, deleted or re-activated.");
        Line("    - IDs are generated by the database; relationships are resolved by slug.");
        Line("    - Runs in a single transaction (XACT_ABORT ON): it either completes or changes nothing.");
        Line("");
        Line("  Data notes");
        Line("    - Prototype content. Opening hours, entrance fees and visit durations are UNVERIFIED demo");
        Line("      estimates. Coordinates flagged CoordinatesApproximate = 1 are best-effort estimates.");
        Line("    - Images are hotlinked from Wikimedia Commons (credited); they are not hosted by this API.");
        Line("    - The runtime seeder (Database:SeedOnStartup) inserts exactly the same records.");
        Line("*/");
        Line();
        Line("SET NOCOUNT ON;");
        Line("SET XACT_ABORT ON;");
        Line("-- Required for writes to tables with filtered indexes; sqlcmd defaults QUOTED_IDENTIFIER to OFF.");
        Line("SET ANSI_NULLS ON;");
        Line("SET QUOTED_IDENTIFIER ON;");
        Line();
        Line("IF OBJECT_ID(N'[dbo].[Attractions]', N'U') IS NULL");
        Line("    THROW 50000, N'Table dbo.Attractions does not exist. Apply the EF Core migrations before running this script.', 1;");
        Line();
        Line("BEGIN TRANSACTION;");
        Line();
        Line("DECLARE @Now datetime2 = SYSUTCDATETIME();");
        Line("DECLARE @AttractionId int;");
        Line();

        Line("/* ---- Attraction categories ---- */");
        foreach (var c in SeedData.Categories)
        {
            Line($"IF NOT EXISTS (SELECT 1 FROM [dbo].[AttractionCategories] WHERE [Slug] = {Str(c.Slug)})");
            Line("    INSERT INTO [dbo].[AttractionCategories] ([Slug], [Name], [Description], [DisplayOrder], [IsActive])");
            Line($"    VALUES ({Str(c.Slug)}, {Str(c.Name)}, NULL, {c.DisplayOrder}, 1);");
        }
        Line();

        Line("/* ---- Start points ---- */");
        foreach (var p in SeedData.StartPresets)
        {
            Line($"IF NOT EXISTS (SELECT 1 FROM [dbo].[StartPresets] WHERE [Slug] = {Str(p.Slug)})");
            Line("    INSERT INTO [dbo].[StartPresets] ([Slug], [Label], [Description], [Latitude], [Longitude], [CoordinatesApproximate], [IsDefault], [DisplayOrder], [IsActive])");
            Line($"    VALUES ({Str(p.Slug)}, {Str(p.Label)}, {Str(p.Description)}, {Num(p.Latitude)}, {Num(p.Longitude)}, " +
                 $"{Bit(p.CoordinatesApproximate)}, {Bit(p.IsDefault)}, {p.DisplayOrder}, 1);");
        }
        Line();

        Line("/* ---- Attractions (inserted one by one so IDs follow catalogue order) ---- */");
        foreach (var a in SeedData.Attractions)
        {
            var searchText = SearchTextNormalizer.BuildAttractionSearchText(a.Name, a.Area, categoryNames[a.Category], a.Tags);
            Line($"-- {a.Name}");
            Line($"IF NOT EXISTS (SELECT 1 FROM [dbo].[Attractions] WHERE [Slug] = {Str(a.Slug)})");
            Line("BEGIN");
            Line($"    INSERT INTO [dbo].[Attractions] ({AttractionColumns})");
            Line("    SELECT");
            Line($"        {Str(a.Name)}, {Str(a.Slug)}, c.[Id],");
            Line($"        {Str(a.ShortDescription)},");
            Line($"        {Json(a.Description)},");
            Line($"        {Str(CommonsImage.Url(a.ImagePath))},");
            Line($"        {Str(a.ImageAlt)},");
            Line($"        {Str(CommonsImage.CreditLabel)}, {Str(CommonsImage.SourceUrl(a.ImagePath))},");
            Line($"        {Str(a.Address)}, {Str(a.Area)}, {Num(a.Latitude)}, {Num(a.Longitude)}, {Bit(a.CoordinatesApproximate)},");
            Line($"        {(a.EstimatedVisitDurationMinutes?.ToString(CultureInfo.InvariantCulture) ?? "NULL")}, {Str(a.OpeningHours)}, {Str(a.EntranceFee)},");
            Line($"        {Json(a.VisitorTips)},");
            Line($"        {Json(a.Tags)},");
            Line($"        {Str(searchText)},");
            Line($"        {Bit(a.Featured)}, 1, @Now, @Now");
            Line("    FROM [dbo].[AttractionCategories] AS c");
            Line($"    WHERE c.[Slug] = {Str(a.Category)};");
            Line();
            Line("    IF @@ROWCOUNT = 0");
            Line($"        THROW 50001, N'Category \"{a.Category}\" is missing; cannot insert attraction \"{a.Slug}\".', 1;");
            Line();
            Line("    SET @AttractionId = SCOPE_IDENTITY();");
            if (a.Gallery.Length > 0)
            {
                Line("    INSERT INTO [dbo].[AttractionImages] ([AttractionId], [Url], [AltText], [CreditLabel], [CreditSourceUrl], [SortOrder])");
                Line("    VALUES");
                for (var i = 0; i < a.Gallery.Length; i++)
                {
                    var g = a.Gallery[i];
                    var separator = i == a.Gallery.Length - 1 ? ";" : ",";
                    Line($"        (@AttractionId, {Str(CommonsImage.Url(g.CommonsPath))}, {Str(g.Alt)}, " +
                         $"{Str(CommonsImage.CreditLabel)}, {Str(CommonsImage.SourceUrl(g.CommonsPath))}, {i + 1}){separator}");
                }
            }
            Line("END;");
            Line();
        }

        Line("COMMIT TRANSACTION;");
        Line();
        Line("PRINT N'Kandy Day Trip Planner seed script completed.';");
        return sql.ToString();
    }

    private static string Str(string? value) => value is null ? "NULL" : $"N'{value.Replace("'", "''")}'";

    private static string Json(IEnumerable<string> values) => Str(JsonSerializer.Serialize(values, JsonOptions));

    private static string Num(double value) => value.ToString("R", CultureInfo.InvariantCulture);

    private static string Bit(bool value) => value ? "1" : "0";
}
